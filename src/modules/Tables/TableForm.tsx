import { Field } from "@/components/ui/Field";
import type { TableFormProps } from "@/types/tables";
import { useTableForm } from "./useTableForm";

export function TableForm({ table, onClose }: TableFormProps) {
  const { register, errors, isSubmitting, error, submit } = useTableForm({
    table,
    onClose,
  });

  return (
    <form className="menu-editor" onSubmit={submit}>
      <div className="editor-grid">
        <Field
          id="table-name"
          label="Table name"
          maxLength={100}
          error={errors.name?.message}
          {...register("name")}
        />
        <Field
          id="table-limit"
          label="Orders per session"
          type="number"
          min={1}
          max={2_147_483_647}
          error={errors.orderLimit?.message}
          {...register("orderLimit", { valueAsNumber: true })}
        />
      </div>
      <p>
        Changing a table’s limit affects its current and future sessions. New
        tables start active; the QR code is generated by the API.
      </p>
      {error && (
        <p className="error" role="alert">
          {error}
        </p>
      )}
      <div className="action-row">
        <button type="submit" className="button" disabled={isSubmitting}>
          {isSubmitting ? "Saving…" : table ? "Save changes" : "Create table"}
        </button>
        <button
          type="button"
          className="button button-outline"
          onClick={onClose}
        >
          Cancel
        </button>
      </div>
    </form>
  );
}

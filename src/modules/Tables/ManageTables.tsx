"use client";

import { useState } from "react";
import Link from "next/link";
import { useForm } from "react-hook-form";
import { zodResolver } from "@hookform/resolvers/zod";
import { useQuery, useQueryClient } from "@tanstack/react-query";
import { toast } from "sonner";
import type { z } from "zod";
import {
  createTable,
  downloadQr,
  downloadQrSheet,
  listManagedTables,
  updateTable,
  type ManagedTable,
  type QrFormat,
} from "@/api/tables";
import { Field } from "@/components/ui/Field";
import { useAuthStore } from "@/lib/auth-state";
import { staffKeys, useStaffRealtime } from "@/modules/Staff/useStaffRealtime";
import { tableSchema } from "./schema";
import { saveAttachment } from "@/lib/save-attachment";

function TableForm({
  table,
  onClose,
}: {
  table?: ManagedTable;
  onClose: () => void;
}) {
  const queryClient = useQueryClient();
  const [error, setError] = useState("");
  const {
    register,
    handleSubmit,
    formState: { errors, isSubmitting },
  } = useForm<z.infer<typeof tableSchema>>({
    resolver: zodResolver(tableSchema),
    defaultValues: {
      name: table?.name ?? "",
      orderLimit: table?.orderLimit ?? 5,
    },
  });
  return (
    <form
      className="menu-editor"
      onSubmit={handleSubmit(async (input) => {
        setError("");
        try {
          if (table) await updateTable(table.id, input);
          else await createTable({ ...input, active: true });
          await Promise.all([
            queryClient.invalidateQueries({
              queryKey: staffKeys.managedTables,
            }),
            queryClient.invalidateQueries({ queryKey: staffKeys.tables }),
          ]);
          toast.success(table ? "Table updated." : "Table created.");
          onClose();
        } catch (cause) {
          setError(
            cause instanceof Error ? cause.message : "Could not save table.",
          );
        }
      })}
    >
      <h2>{table ? `Edit ${table.name}` : "Add physical table"}</h2>
      <div className="editor-grid">
        <Field
          id="table-name"
          label="Table name"
          maxLength={100}
          error={errors.name?.message}
          {...register("name")}
        />
        <Field
          id="table-limit"
          label="Orders per session"
          type="number"
          min={1}
          max={2_147_483_647}
          error={errors.orderLimit?.message}
          {...register("orderLimit", { valueAsNumber: true })}
        />
      </div>
      <p>
        Changing a table’s limit affects its current and future sessions. New
        tables start active; the QR code is generated by the API.
      </p>
      {error && (
        <p className="error" role="alert">
          {error}
        </p>
      )}
      <div className="action-row">
        <button type="submit" className="button" disabled={isSubmitting}>
          {isSubmitting ? "Saving…" : table ? "Save changes" : "Create table"}
        </button>
        <button
          type="button"
          className="button button-outline"
          onClick={onClose}
        >
          Cancel
        </button>
      </div>
    </form>
  );
}

function TableCard({ table }: { table: ManagedTable }) {
  const queryClient = useQueryClient();
  const [editing, setEditing] = useState(false);
  const [confirming, setConfirming] = useState(false);
  const [saving, setSaving] = useState(false);
  const [downloading, setDownloading] = useState<QrFormat | null>(null);
  const target = new URL(table.qrUrl);
  const saveQr = async (format: QrFormat) => {
    setDownloading(format);
    try {
      saveAttachment(
        await downloadQr(table.id, format),
        `table-${table.id}.${format}`,
      );
    } catch (cause) {
      toast.error(
        cause instanceof Error ? cause.message : "Could not download QR code.",
      );
    } finally {
      setDownloading(null);
    }
  };
  const changeActivation = async () => {
    setSaving(true);
    try {
      await updateTable(table.id, { active: !table.active });
      await Promise.all([
        queryClient.invalidateQueries({ queryKey: staffKeys.managedTables }),
        queryClient.invalidateQueries({ queryKey: staffKeys.tables }),
      ]);
      toast.success(
        table.active
          ? `${table.name} deactivated.`
          : `${table.name} reactivated.`,
      );
      setConfirming(false);
    } catch (cause) {
      toast.error(
        cause instanceof Error
          ? cause.message
          : "Could not change table status.",
      );
    } finally {
      setSaving(false);
    }
  };
  return (
    <article className="managed-table">
      <div className="section-heading">
        <div>
          <span className="eyebrow">TABLE {table.id}</span>
          <h2>{table.name}</h2>
        </div>
        <span
          className={`status-tag ${table.active ? "status-open" : "status-served"}`}
        >
          {table.active ? "Active" : "Inactive"}
        </span>
      </div>
      <p>
        Order limit: <strong>{table.orderLimit} per session</strong>
      </p>
      <p className="qr-target">
        QR destination:{" "}
        <code>
          {target.origin}
          {target.pathname}
        </code>
        <span>Token hidden · verify the customer origin before printing.</span>
      </p>
      <div className="action-row">
        <button
          type="button"
          className="button button-outline"
          onClick={() => setEditing(!editing)}
        >
          {editing ? "Close editor" : "Edit name & limit"}
        </button>
        <button
          type="button"
          className="button button-outline"
          disabled={saving}
          onClick={() => setConfirming(!confirming)}
        >
          {table.active ? "Deactivate" : "Reactivate"}
        </button>
      </div>
      {table.active && (
        <div className="action-row">
          <button
            type="button"
            className="button button-outline"
            disabled={downloading !== null}
            onClick={() => void saveQr("png")}
          >
            {downloading === "png" ? "Downloading…" : "Download PNG"}
          </button>
          <button
            type="button"
            className="button button-outline"
            disabled={downloading !== null}
            onClick={() => void saveQr("svg")}
          >
            {downloading === "svg" ? "Downloading…" : "Download SVG"}
          </button>
        </div>
      )}
      {!table.active && (
        <p className="error">Reactivate to download this table’s QR code.</p>
      )}
      {confirming && (
        <div className="action-panel">
          <p>
            {table.active
              ? "Deactivate this table? Its QR code will no longer resolve. Existing sessions are not closed by this change."
              : "Reactivate this table? Its existing QR code will work again."}
          </p>
          <div className="action-row">
            <button
              type="button"
              className={`button ${table.active ? "button-danger" : ""}`}
              disabled={saving}
              onClick={() => void changeActivation()}
            >
              {saving
                ? "Saving…"
                : table.active
                  ? "Confirm deactivation"
                  : "Confirm reactivation"}
            </button>
            <button
              type="button"
              className="button button-outline"
              onClick={() => setConfirming(false)}
            >
              Keep as is
            </button>
          </div>
        </div>
      )}
      {editing && (
        <TableForm
          key={table.id}
          table={table}
          onClose={() => setEditing(false)}
        />
      )}
    </article>
  );
}

function ManagerTables() {
  const [filter, setFilter] = useState<"all" | "active" | "inactive">("all");
  const [creating, setCreating] = useState(false);
  const [sheetPending, setSheetPending] = useState(false);
  const query = useQuery({
    queryKey: staffKeys.managedTables,
    queryFn: ({ signal }) => listManagedTables(signal),
  });
  const transport = useStaffRealtime();
  const visible = query.data?.filter(
    (table) => filter === "all" || table.active === (filter === "active"),
  );
  const sheet = async () => {
    setSheetPending(true);
    try {
      saveAttachment(await downloadQrSheet(), "enjoyer-table-qr-codes.html");
    } catch (cause) {
      toast.error(
        cause instanceof Error ? cause.message : "Could not download QR sheet.",
      );
    } finally {
      setSheetPending(false);
    }
  };
  return (
    <div>
      <div className="page-head board-heading">
        <div>
          <span className="eyebrow">ENJOYER / TABLE MANAGEMENT</span>
          <h1>
            Manage tables<span className="brand-dot">.</span>
          </h1>
          <p>
            Create physical tables, control order limits and print their QR
            codes.
          </p>
        </div>
        <span className="eyebrow" role="status">
          {transport === "sse"
            ? "● Live"
            : transport === "polling"
              ? "◌ Polling fallback"
              : "Connecting…"}
        </span>
      </div>
      <div className="table-manage-controls">
        <label className="field">
          <span className="eyebrow">Table status</span>
          <select
            value={filter}
            onChange={(event) => setFilter(event.target.value as typeof filter)}
          >
            <option value="all">All tables</option>
            <option value="active">Active</option>
            <option value="inactive">Inactive</option>
          </select>
        </label>
        <button
          type="button"
          className="button"
          onClick={() => setCreating(true)}
        >
          Add table
        </button>
        <button
          type="button"
          className="button button-outline"
          disabled={sheetPending}
          onClick={() => void sheet()}
        >
          {sheetPending ? "Downloading…" : "Download printable QR sheet"}
        </button>
      </div>
      <p className="table-help">
        The sheet contains only active tables. Open the downloaded HTML file in
        a browser and select Print. QR codes point to the API-configured{" "}
        <code>CUSTOMER_URL</code> (or <code>CLIENT_URL</code> fallback). The
        customer app is not built yet; configure and verify its{" "}
        <code>/order</code> page before printing QR codes for service.{" "}
        <Link className="text-button" href="/tables">
          View live table sessions →
        </Link>
      </p>
      {creating && <TableForm onClose={() => setCreating(false)} />}
      {query.isPending && (
        <p role="status" className="feature-note">
          Loading tables…
        </p>
      )}
      {query.isError && (
        <div className="feature-note error" role="alert">
          {query.error.message}{" "}
          <button
            type="button"
            className="text-button"
            onClick={() => void query.refetch()}
          >
            Retry
          </button>
        </div>
      )}
      {visible?.length === 0 && (
        <p className="feature-note">
          {filter === "all"
            ? "No tables have been created yet."
            : "No tables match this filter."}
        </p>
      )}
      {visible && (
        <div className="managed-table-grid">
          {visible.map((table) => (
            <TableCard key={table.id} table={table} />
          ))}
        </div>
      )}
    </div>
  );
}

export default function ManageTables() {
  const role = useAuthStore((s) => s.user?.role);
  if (role !== "owner" && role !== "manager")
    return (
      <div className="feature-note" role="alert">
        <h1>Access restricted</h1>
        <p>Only a Manager or Owner can manage tables and QR codes.</p>
        <Link className="text-button" href="/tables">
          View live tables
        </Link>
      </div>
    );
  return <ManagerTables />;
}
